    cgroup_reparent_procs "${_cg}" "${_cg}/init"
    cgroup_delegate_controllers "${_cg}"

    cgroup_reparent_procs "${_cg}/.lxc" "${_cg}/.lxc/init"
    cgroup_delegate_controllers "${_cg}/.lxc"

    eend 0
