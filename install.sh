            systemd) stop_systemd ;;
            openrc) stop_openrc ;;
            procd) stop_procd ;;
            sysvinit) stop_sysvinit ;;
            upstart) stop_upstart ;;
            s6) stop_s6 ;;
            runit) stop_runit ;;
            *) stop_fallback ;;
