}

detect_arch() {
    MACHINE=$(uname -m)
    case "${MACHINE}" in
        x86_64|amd64)     echo "amd64" ;;
        aarch64|arm64)    echo "arm64" ;;
        armv7l|armv6l|arm) echo "arm" ;;
        riscv64)          echo "riscv64" ;;
        *) die "Unsupported architecture: ${MACHINE}" ;;
    esac
