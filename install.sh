stop_edgelet_daemon_desktop() {
    _os="$1"
    case "${_os}" in
        darwin|windows) ;;
        *) return 0 ;;
    esac
    if pgrep -f '[e]dgelet daemon' >/dev/null 2>&1; then
        pkill -f '[e]dgelet daemon' 2>/dev/null || true
        sleep 1
        info "edgelet daemon stopped."
    fi
    case "${_os}" in
        darwin) rm -f /var/run/edgelet/edgelet.pid ;;
        windows) rm -f "$(windows_program_data_edgelet)/run/edgelet.pid" ;;
    esac
}

start_edgelet_daemon_desktop() {
    _os="$1"
    _log_dir="/var/log/edgelet"
    _pid_file="/var/run/edgelet/edgelet.pid"
    case "${_os}" in
        darwin)
            mkdir -p "$_log_dir" /var/run/edgelet
            ;;
        windows)
            _pd=$(windows_program_data_edgelet)
            _log_dir="${_pd}/log"
            _pid_file="${_pd}/run/edgelet.pid"
            mkdir -p "$_log_dir" "$(dirname "$_pid_file")"
            ;;
        *) return 0 ;;
    esac

    if pgrep -f '[e]dgelet daemon' >/dev/null 2>&1; then
        info "edgelet daemon already running"
        return 0
    fi

    nohup edgelet daemon &
    echo $! > "$_pid_file"
    info "edgelet daemon started in background (pid=$(cat "$_pid_file"))"
    info "  logs: ${_log_dir}/edgelet.0.log"
}

