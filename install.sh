        $0 stop
        $0 start
        ;;
    status)
        status_of_proc -p "$PIDFILE" "$DAEMON" edgelet
        ;;
    *)
        echo "Usage: $0 {start|stop|restart|status}"
        exit 1
        ;;
esac

exit 0
EDGELET_SYSVINIT_EDGELET_EOF
    chmod 755 "/etc/init.d/edgelet"
}
