    if [ -f "${_dest}" ]; then
        # shellcheck disable=SC2016
        awk -v need="${_need}" '
            /%%EDGELET_ENGINE_NEED%%/ {
                if (need != "") print need
                next
            }
            { print }
        ' "${_dest}" > "${_dest}.tmp" && mv "${_dest}.tmp" "${_dest}"
    fi
}

