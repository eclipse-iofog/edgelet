            || [ "${SCRIPT_DIR}/install.sh" = "$_dest" ]; then
            return 0
        fi
        install -m 755 "${SCRIPT_DIR}/install.sh" "$_dest"
        return 0
    fi
    case "$0" in
        */install.sh)
            if [ -f "$0" ]; then
                if [ "$0" -ef "$_dest" ] 2>/dev/null || [ "$0" = "$_dest" ]; then
                    return 0
                fi
                install -m 755 "$0" "$_dest"
                return 0
            fi
            ;;
    esac
    write_embedded_install "$_dest"
}

