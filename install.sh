### BEGIN INIT INFO
# Provides:          edgelet
# Required-Start:    $network $remote_fs
# Required-Stop:     $network $remote_fs
# Default-Start:     2 3 4 5
# Default-Stop:      0 1 6
# Short-Description: Edgelet daemon
### END INIT INFO

DAEMON=/usr/local/bin/edgelet
SHUTDOWN=/usr/libexec/edgelet/edgelet-shutdown
