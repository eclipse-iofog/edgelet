case "$1" in
    start)
        log_daemon_msg "Starting edgelet"
        preflight || exit $?
        start-stop-daemon --start --background --make-pidfile --pidfile "$PIDFILE" \
            --exec "$DAEMON" -- daemon >>"$LOGFILE" 2>&1
        log_end_msg $?
        ;;
    stop)
        log_daemon_msg "Stopping edgelet"
        if [ -x "$SHUTDOWN" ]; then
            "$SHUTDOWN" && log_end_msg 0 && exit 0
